C> @brief ANSI FORTRAN 66 streaming upload callback producing 4 bytes.
      INTEGER FUNCTION F6RDCK(IUID, BUF, ICAP, NOUT)
      INTEGER IUID, BUF(1), ICAP, NOUT, IHUP
      INTEGER NUPLD
      COMMON /F6TCOM/ NUPLD
      DATA IHUP /4HF66!/
      IF (NUPLD .GT. 0 .OR. ICAP .LT. 4) GOTO 10
      BUF(1) = IHUP + (IUID - IUID)
      NOUT = 4
      NUPLD = 1
      F6RDCK = 0
      RETURN
