      INTEGER F4CHUK, F4PROG, F4WMSG, F4WERR, F4WCLS
      INTEGER F4SEVT, F4SERR, F4SCLS
      EXTERNAL F4CHUK, F4PROG, F4WMSG, F4WERR, F4WCLS
      EXTERNAL F4SEVT, F4SERR, F4SCLS
      EXTERNAL FAH4BD
      INTEGER IDEFTM, IDEF62
      LOGICAL LDEFVP, LDEFRD
      COMMON /FAH4CM/ IDEFTM, IDEF62, LDEFVP, LDEFRD
      INTEGER NCHIT, NWHIT, NSHIT
      COMMON /F4TCOM/ NCHIT, NWHIT, NSHIT
      INTEGER IHGINI, IHGCLN, IHCLCR, IHCLFR, IHCFFR
      INTEGER IHMKST, IHMKSP, IHMKUL
      INTEGER IHURL(32), ICFG, ICLI, IPORT, ISTS, IERR, IDM
C
      NCHIT = 0
      NWHIT = 0
      NSHIT = 0
      IF (IDEF62 .NE. 1962) STOP 1
      IF (IHGINI(0) .NE. 0) STOP 1
      IF (IHMKST(IPORT) .NE. 0) STOP 1
C
      CALL FH4CFG(0, .TRUE., .TRUE., 1, ICFG, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL FH4CFG(0, .FALSE., .FALSE., -1, IDM, IERR)
      IF (IERR .EQ. 0) STOP 1
C
      IF (IHCLCR(ICFG, 1, ICLI) .NE. 0) STOP 1
      IDM = IHMKUL(IPORT, 2, 1, IHURL, NURL)
      CALL FH4STR(ICLI, IHURL, NURL, F4CHUK, 1, F4PROG, 1, ISTS, IERR)
      IF (IERR .NE. 0 .OR. ISTS .NE. 200 .OR. NCHIT .LE. 0) STOP 1
      CALL FH4STR(0, IHURL, NURL, F4CHUK, 1, F4PROG, 1, ISTS, IERR)
      IF (IERR .EQ. 0) STOP 1
C
      IDM = IHMKUL(IPORT, 3, 1, IHURL, NURL)
      CALL FH4WSS(ICLI, IHURL, NURL, F4WMSG, F4WERR, F4WCLS, 1, IERR)
      IF (IERR .NE. 0 .OR. NWHIT .LE. 0) STOP 1
C
      IDM = IHMKUL(IPORT, 4, 1, IHURL, NURL)
      CALL FH4SSE(ICLI, IHURL, NURL, F4SEVT, F4SERR, F4SCLS, 1, IERR)
      IF (IERR .NE. 0 .OR. NSHIT .LT. 2) STOP 1
C
      IDM = IHCLFR(ICLI)
      IDM = IHCFFR(ICFG)
      IDM = IHMKSP(IPORT)
      IDM = IHGCLN(0)
      STOP
      END
C> @brief FORTRAN IV download chunk callback.
      INTEGER FUNCTION F4CHUK(IUID, BUF, NLEN)
      INTEGER IUID, BUF(1), NLEN
      INTEGER NCHIT, NWHIT, NSHIT
      COMMON /F4TCOM/ NCHIT, NWHIT, NSHIT
      NCHIT = NCHIT + NLEN + IUID - IUID + BUF(1) - BUF(1)
      F4CHUK = 0
      RETURN
      END
C> @brief FORTRAN IV progress callback.
      INTEGER FUNCTION F4PROG(ICUR, ITOT, IUID)
      INTEGER ICUR, ITOT, IUID
      F4PROG = (ICUR - ICUR) + (ITOT - ITOT) + (IUID - IUID)
      RETURN
      END
C> @brief FORTRAN IV WebSocket message callback.
      INTEGER FUNCTION F4WMSG(IOP, BUF, NLEN, IFIN, IUID)
      INTEGER IOP, BUF(1), NLEN, IFIN, IUID
      INTEGER NCHIT, NWHIT, NSHIT
      COMMON /F4TCOM/ NCHIT, NWHIT, NSHIT
      NWHIT = NWHIT + 1 + (IOP - IOP) + (IFIN - IFIN) + (IUID - IUID)
      IF (NLEN .LT. 0 .AND. BUF(1) .EQ. 0) NWHIT = 0
      F4WMSG = 0
      RETURN
      END
C> @brief FORTRAN IV WebSocket error callback.
      INTEGER FUNCTION F4WERR(IERR, IUID)
      INTEGER IERR, IUID
      F4WERR = (IERR - IERR) + (IUID - IUID)
      RETURN
      END
C> @brief FORTRAN IV WebSocket close callback.
      INTEGER FUNCTION F4WCLS(ISTS, IUID)
      INTEGER ISTS, IUID
      F4WCLS = (ISTS - ISTS) + (IUID - IUID)
      RETURN
      END
C> @brief FORTRAN IV SSE event callback.
      INTEGER FUNCTION F4SEVT(IDB, IDL, EVB, EVL, DTB, DTL, IUID)
      INTEGER IDB(1), IDL, EVB(1), EVL, DTB(1), DTL, IUID
      INTEGER NCHIT, NWHIT, NSHIT
      COMMON /F4TCOM/ NCHIT, NWHIT, NSHIT
      NSHIT = NSHIT + 1 + (IDL - IDL) + (EVL - EVL) + (DTL - DTL)
      IF (IUID .EQ. -9 .AND. IDB(1) .EQ. EVB(1) .AND. DTB(1) .EQ. 0)
     1 NSHIT = 0
      F4SEVT = 0
      RETURN
      END
C> @brief FORTRAN IV SSE error callback.
      INTEGER FUNCTION F4SERR(IERR, IUID)
      INTEGER IERR, IUID
      F4SERR = (IERR - IERR) + (IUID - IUID)
      RETURN
      END
C> @brief FORTRAN IV SSE close callback.
      INTEGER FUNCTION F4SCLS(IUID)
      INTEGER IUID
      F4SCLS = IUID - IUID
      RETURN
      END
