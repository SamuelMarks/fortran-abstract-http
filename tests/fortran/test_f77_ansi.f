C> @file test_f77_ansi.f
C> @brief Integration test suite for ANSI X3.9-1978 (FORTRAN 77) layer.
      PROGRAM TF77
      INCLUDE 'fah77.inc'
      INCLUDE 'c_abstract_http_f77.inc'
      INTEGER IHMKST, IHMKSP
      INTEGER IPORT, ICFG, ICLI, IREQ, IRES, ISTS, NLEN, IERR, ICAT, IDM
      CHARACTER*128 URL, OUTB, HVAL, EMSG
      LOGICAL LRETRY
C
      CALL FH7INI(IERR)
      IF (IERR .NE. IHEOK .OR. IHEOK .NE. CAHOK) STOP 1
      IF (IHMKST(IPORT) .NE. 0) STOP 1
C
      CALL FH7CCR(ICFG, IERR)
      IF (IERR .NE. IHEOK) STOP 1
      CALL FH7CLC(ICFG, 1, ICLI, IERR)
      IF (IERR .NE. IHEOK) STOP 1
      CALL FH7CFR(ICFG, IERR)
      IF (IERR .NE. IHEOK) STOP 1
C
      CALL FHMKS7(IPORT, '/hello', URL, NLEN)
      CALL FHSGET(ICLI, URL, OUTB, ISTS, NLEN, IERR)
      IF (IERR .NE. IHEOK .OR. ISTS .NE. 200) STOP 1
      IF (OUTB(1:13) .NE. 'Hello FORTRAN') STOP 1
      CALL FHSGET(0, URL, OUTB, ISTS, NLEN, IERR)
      IF (IERR .EQ. IHEOK) STOP 1
C
      CALL FHMKS7(IPORT, '/echo', URL, NLEN)
      CALL FHSPST(ICLI, URL, 'text/plain', 'F77-POST', OUTB, ISTS,
     1 NLEN, IERR)
      IF (IERR .NE. IHEOK .OR. OUTB(1:8) .NE. 'F77-POST') STOP 1
      CALL FHSPST(0, URL, 'text/plain', 'X', OUTB, ISTS, NLEN, IERR)
      IF (IERR .EQ. IHEOK) STOP 1
C
      CALL FH7RCR(IREQ, IERR)
      CALL FH7RTG(IREQ, IHMPST, URL, IERR)
      CALL FH7RHD(IREQ, 'X-Custom', 'val77', IERR)
      CALL FH7RBB(IREQ, 'RAW77', 5, IERR)
      CALL FH7SND(ICLI, IREQ, IRES, ISTS, NLEN, IERR)
      IF (IERR .NE. IHEOK .OR. ISTS .NE. 200) STOP 1
      CALL FH7RSB(IRES, OUTB, NLEN, IERR)
      IF (OUTB(1:5) .NE. 'RAW77') STOP 1
      CALL FH7RSH(IRES, 'X-Echo-Custom', HVAL, NLEN, IERR)
      IF (HVAL(1:5) .NE. 'val77') STOP 1
      CALL FH7RSF(IRES, 'f77_out.tmp', 1, IERR)
      IF (IERR .NE. IHEOK) STOP 1
      CALL FH7RFR(IREQ, IERR)
C
      CALL FH7RCR(IREQ, IERR)
      CALL FH7RTG(IREQ, IHMPST, URL, IERR)
      CALL FH7RPT(IREQ, 'p1', 'f.txt', 'text/plain', 'MP77', 4, IERR)
      CALL FH7SND(ICLI, IREQ, IRES, ISTS, NLEN, IERR)
      IF (IERR .NE. IHEOK) STOP 1
      CALL FH7RSF(IRES, ' ', 1, IERR)
      CALL FH7RFR(IREQ, IERR)
C
      CALL FH7FMT(IHETMO, 'TF77', EMSG, ICAT, LRETRY, NLEN, IERR)
      IF (.NOT. LRETRY .OR. NLEN .LE. 0) STOP 1
C
      CALL FH7CLF(ICLI, IERR)
      IDM = IHMKSP(IPORT)
      CALL FH7CLN(IERR)
      STOP
      END
